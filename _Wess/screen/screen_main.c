// Get
U08 SCRN_GetScrnIdx(void)		{	return lScr_idx;		}
// Set


//------------------------------------------------------------------------------------------------------------------------------
//  Global APIs - Operation
//------------------------------------------------------------------------------------------------------------------------------
void SCRN_InitVari(void)
{
	lScr_idx = SCR_I00_IDLE + 1;

	ScTRD_InitVai();
}

void SCRN_ProcKey(U08 key)
{
	switch(key)
	{
		case BTN_IDX_RIGHT:
			if(++lScr_idx >= SCR_IDX_MAX)
				lScr_idx = SCR_I00_IDLE + 1;
			break;

		case BTN_IDX_LEFT:
			if(lScr_idx == SCR_I00_IDLE + 1)		lScr_idx = SCR_IDX_MAX - 1;
			else									lScr_idx--;
			break;
	}
}

void SCRN_ProcDisp(void)
{
	if(gTd_f_en)
	{
		LDT_UpdBuff(LCD_Y_START, LCD_Y_END);
		return;
	}

	LDT_ClrBuff(LCD_X_START, LCD_Y_START, LCD_X_END, LCD_Y_END);

	switch(lScr_idx)
	{
		case SCR_I01_FRONT:			DpFRT_ProcMain();				break;
		case SCR_I02_GRP_LIVE:
		case SCR_I03_GRP_AVRG:		DpGRP_ProcMain(lScr_idx);		break;
		case SCR_I04_INFO:			DpINF_ProcMain();				break;
		default:					return;
	}

	LDT_UpdBuff(LCD_Y_START, LCD_Y_END);
}


