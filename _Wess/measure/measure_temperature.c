void MsTPR_InitVari(void)
{
	gTp_now = 0;

	lTp_cnt = 0;
}

void MsTPR_CalcVal(void)
{
	U08 i;
	S16 sum = 0;
	F32 dat[2];

	dat[0] = AD0_GetRegs(0);
	dat[1] = (-29.474 * log(dat[0])) + 196.03;

	lTp_buff[lTp_cnt] = dat[1] * 10;
	lTp_cnt = (lTp_cnt + 1) % 4;

	for(i=0; i<4; i++) 
	    sum += lTp_buff[i];

	gTp_deg = sum / 4;

	if(MnMSR_GetUnit() == MnMSR_UNIT_METER)
	{
		gTp_now = gTp_deg;
		return;
	}

	lTp_Fah = (gTp_deg * 1.8) + 320;
	gTp_now = lTp_Fah;
}


